import test from "node:test";
import assert from "node:assert/strict";
import { createInitialData } from "../src/initialData.ts";
import { episodes, progress, completedRounds } from "../src/model.ts";
import { browserRepository, STORAGE_KEY, validData } from "../src/storage.ts";

test("provided EBS/Basic history has no invented actual dates or times", () => {
  const d = createInitialData();
  assert.equal(d.logs.length, 22);
  assert.ok(
    d.logs.every(
      (l) => l.date === null && l.minutes === null && l.origin === "reported",
    ),
  );
  assert.equal(d.logs.filter((l) => l.materialId === "basic").length, 6);
  assert.deepEqual(
    d.materials
      .filter((m) => m.kind === "audio")
      .map((m) => d.logs.filter((l) => l.materialId === m.id).length),
    [5, 5, 6],
  );
  assert.ok(!d.materials.some((m) => m.area !== "english"));
  assert.ok(validData(d));
});
test("EBS schedules exclude weekends as configured without equating publication and learning dates", () => {
  const [start, , power] = createInitialData().materials;
  assert.equal(episodes(start, "2026-04").length, 22);
  assert.equal(episodes(power, "2026-04").length, 26);
  assert.ok(!episodes(start, "2026-04").includes("2026-04-04"));
  assert.ok(episodes(power, "2026-04").includes("2026-04-04"));
  assert.equal(episodes(start, "2026-03").length, 0);
});
test("per-round progress uses unique completed units and excludes organization work", () => {
  const d = createInitialData(),
    m = d.materials.find((m) => m.id === "basic"),
    first = d.logs.find((l) => l.materialId === "basic");
  assert.equal(progress(m, d.logs).count, 6);
  assert.equal(
    progress(
      d.materials.find((m) => m.id === "vocabulary"),
      d.logs,
    ).percent,
    null,
  );
  assert.equal(progress(m, d.logs, 11).percent, null);
  const logs = [
    ...d.logs,
    { ...first, id: "repeat" },
    { ...first, id: "org", item: "7", activity: "system" },
    { ...first, id: "incomplete", item: "8", completed: false },
  ];
  assert.equal(progress(m, logs).count, 6);
  assert.equal(completedRounds(m, logs), 0);
  assert.equal(progress({ ...m, total: 3 }, logs).count, 3);
  assert.equal(logs.length, 25);
});
test("round 11 and beyond are independent of target 10 and preserve earlier entries", () => {
  const d = createInitialData(),
    m = {
      ...d.materials.find((m) => m.id === "basic"),
      total: 2,
      targetPasses: 10,
    };
  const first = d.logs.find((l) => l.materialId === "basic");
  const logs = [
    ...d.logs,
    { ...first, id: "r11a", round: 11, item: "1" },
    { ...first, id: "r11b", round: 11, item: "2" },
  ];
  assert.equal(progress(m, logs, 11).count, 2);
  assert.equal(completedRounds(m, logs), 2);
  assert.equal(progress(m, logs, 12).count, 0);
});
test("local repository roundtrips status changes with all records retained; malformed raw storage is preserved", () => {
  const entries = new Map();
  Object.defineProperty(globalThis, "localStorage", {
    configurable: true,
    value: {
      getItem: (k) => entries.get(k) ?? null,
      setItem: (k, v) => entries.set(k, v),
    },
  });
  const d = createInitialData();
  d.materials[0].status = "보류";
  browserRepository.save(d);
  assert.deepEqual(browserRepository.load(), d);
  entries.set(STORAGE_KEY, "{broken");
  assert.throws(() => browserRepository.load());
  assert.equal(entries.get(STORAGE_KEY), "{broken");
  entries.set(
    STORAGE_KEY,
    JSON.stringify({
      version: 1,
      materials: [],
      logs: [{ invalid: true }],
      goals: [],
      tasks: [],
    }),
  );
  assert.throws(() => browserRepository.load());
});
