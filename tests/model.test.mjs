  const d = createInitialData();
  assert.ok(d.goals.every((g) => g.prerequisiteId === ""));
  assert.equal(d.goals.find((g) => g.id === "opic").current, "IM2");
  assert.equal(d.tasks.length, 1);
  assert.equal(d.tasks[0].items.length, 3);
