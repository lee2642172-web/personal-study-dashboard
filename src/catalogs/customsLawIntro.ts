export function createCustomsLawIntro(): Material {
  return {
    id: CUSTOMS_LAW_INTRO_ID,
    title: "관세법개론",
    area: "customs",
    kind: "lectures",
    status: "보관 중",
    total: rows.length,
    targetPasses: null,
    lectures: rows.map(([title, duration], index) => ({
      number: index + 1,
      title,
      duration,
    })),
    schedule: [],
    startDate: "",
    duration: null,
    routine: "관세사 · 관세법개론 강의",
    note: "사용자 제공 98강을 모두 미수강으로 등록했습니다. 괄호 안 강의 길이만 사용하며, 수강 완료 시 해당 시간이 기본 학습시간으로 기록됩니다. 시간은 수정할 수 있습니다.",
  };
}
export function includeCustomsLawIntro(data: DashboardData): DashboardData {
  if (data.materials.some((m) => m.id === CUSTOMS_LAW_INTRO_ID)) return data;
  return { ...data, materials: [...data.materials, createCustomsLawIntro()] };
}
