export function createFinancialAccounting(): Material {
  return {
    id: FINANCIAL_ACCOUNTING_ID,
    title: "재무회계",
    area: "customs",
    kind: "lectures",
    lectureCatalogStatus: "ongoing",
    status: "보관 중",
    total: rows.length,
    targetPasses: null,
    lectures: rows.map(([title, duration], index) => ({
      number: index + 1,
      title,
      duration,
    })),
    schedule: [],
    startDate: "",
    duration: null,
    routine: "관세사 · 재무회계 강의",
    note: "아직 완강되지 않은 과목입니다. 현재 등록된 강의 기준으로 진도를 표시하며, 새 강의는 기존 기록을 유지한 채 추가됩니다. 전부 미수강으로 시작하며, 수강 완료 시 괄호 안 강의시간이 기본 학습시간으로 저장됩니다. 시간은 수정할 수 있습니다.",
  };
}
/** Append newly supplied lecture numbers without replacing saved edits or learning records. */
export function includeFinancialAccounting(data: DashboardData): DashboardData {
  const catalog = createFinancialAccounting();
  const saved = data.materials.find((m) => m.id === FINANCIAL_ACCOUNTING_ID);
  if (!saved) return { ...data, materials: [...data.materials, catalog] };
  const numbers = new Set(saved.lectures?.map((l) => l.number));
  const additions = catalog.lectures!.filter((l) => !numbers.has(l.number));
  if (!additions.length) return data;
  const lectures = [...(saved.lectures ?? []), ...additions].sort(
    (a, b) => a.number - b.number,
  );
  return {
    ...data,
    materials: data.materials.map((m) =>
      m.id === saved.id
        ? {
            ...m,
            lectures,
            total: Math.max(m.total ?? 0, ...lectures.map((l) => l.number)),
          }
        : m,
    ),
  };
}
